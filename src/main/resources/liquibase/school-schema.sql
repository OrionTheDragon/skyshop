CREATE TABLE IF NOT EXISTS faculties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    color VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    age INT NOT NULL
);

ALTER TABLE students ADD COLUMN IF NOT EXISTS faculty_id BIGINT REFERENCES faculties (id);

CREATE TABLE IF NOT EXISTS avatars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_path VARCHAR(255),
    media_type VARCHAR(255)
);

ALTER TABLE avatars
    ADD COLUMN IF NOT EXISTS student_id BIGINT UNIQUE REFERENCES students (id) ON DELETE SET NULL;
